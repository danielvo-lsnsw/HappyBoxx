function getInitialLanguage(): UiLanguage {
  return localStorage.getItem(LANGUAGE_STORAGE_KEY) === 'vi' ? 'vi' : 'en';
}

export function UiLanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<UiLanguage>(getInitialLanguage);

  useEffect(() => {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  const value = {
    language,
    setLanguage,
    t: (englishText: string) =>
      language === 'vi' ? (translations[englishText] ?? englishText) : englishText,
  };

  return <UiLanguageContext.Provider value={value}>{children}</UiLanguageContext.Provider>;
}
